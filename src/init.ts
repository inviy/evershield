/**
 * `evershield init`: turn a one-off scan into a check that runs on every
 * pull request. Detects the framework and build directory, then writes
 * `evershield.config.json` and `.github/workflows/evershield.yml`.
 *
 * Existing files are never overwritten unless `--force` is given; init
 * reports what it skipped instead.
 */
import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

export interface Detection {
  framework: "nextjs" | "vite" | "astro" | "create-react-app" | "nuxt" | "sveltekit" | "unknown";
  /** Build output directory relative to the project root. */
  buildDir: string;
  packageManager: "pnpm" | "yarn" | "bun" | "npm";
  /** Shell command that produces the build directory. */
  buildCommand: string;
  /** package.json pins a version in "packageManager"; pnpm/action-setup fails without it unless told one. */
  packageManagerPinned?: boolean;
}

async function exists(filePath: string): Promise<boolean> {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function anyExists(root: string, names: string[]): Promise<boolean> {
  for (const name of names) if (await exists(path.join(root, name))) return true;
  return false;
}

interface PackageJson {
  dependencies?: Record<string, string>;
  devDependencies?: Record<string, string>;
  scripts?: Record<string, string>;
  packageManager?: string;
}

export async function detectProject(root: string): Promise<Detection> {
  let pkg: PackageJson = {};
  try {
    pkg = JSON.parse(await readFile(path.join(root, "package.json"), "utf8")) as PackageJson;
  } catch {
    // Not a Node project, or no package.json: fall through to defaults.
  }
  const deps = { ...pkg.dependencies, ...pkg.devDependencies };
  const has = (name: string) => deps[name] !== undefined;

  let framework: Detection["framework"] = "unknown";
  let buildDir = "dist";
  if (has("next") || (await anyExists(root, ["next.config.js", "next.config.mjs", "next.config.ts"]))) {
    framework = "nextjs";
    buildDir = ".next";
  } else if (has("nuxt")) {
    framework = "nuxt";
    buildDir = ".output/public";
  } else if (has("@sveltejs/kit")) {
    framework = "sveltekit";
    buildDir = "build";
  } else if (has("astro")) {
    framework = "astro";
    buildDir = "dist";
  } else if (has("react-scripts")) {
    framework = "create-react-app";
    buildDir = "build";
  } else if (has("vite")) {
    framework = "vite";
    buildDir = "dist";
  }

  let packageManager: Detection["packageManager"] = "npm";
  if (await exists(path.join(root, "pnpm-lock.yaml"))) packageManager = "pnpm";
  else if (await exists(path.join(root, "yarn.lock"))) packageManager = "yarn";
  else if (await anyExists(root, ["bun.lockb", "bun.lock"])) packageManager = "bun";

  const run = packageManager === "npm" ? "npm run" : packageManager;
  const buildCommand = pkg.scripts?.build !== undefined ? `${run} build` : "echo 'set your build command here' && exit 1";

  return { framework, buildDir, packageManager, buildCommand, packageManagerPinned: typeof pkg.packageManager === "string" };
}

const INSTALL: Record<Detection["packageManager"], string> = {
  npm: "npm ci",
  pnpm: "pnpm install --frozen-lockfile",
  yarn: "yarn install --frozen-lockfile",
  bun: "bun install --frozen-lockfile",
};

export function renderWorkflow(detection: Detection): string {
  const setup =
    detection.packageManager === "pnpm"
      ? `      - uses: pnpm/action-setup@v4\n${detection.packageManagerPinned === true ? "" : "        with:\n          version: 10\n"}      - uses: actions/setup-node@v4\n        with:\n          node-version: 22\n          cache: pnpm\n`
      : detection.packageManager === "bun"
        ? "      - uses: oven-sh/setup-bun@v2\n"
        : `      - uses: actions/setup-node@v4\n        with:\n          node-version: 22\n          cache: ${detection.packageManager}\n`;

  return `name: evershield

# Scans what your app ships to the browser on every pull request and
# reports findings in the Security tab. Generated by \`evershield init\`.

on:
  pull_request:
  push:
    branches: [main]

permissions:
  contents: read
  security-events: write

jobs:
  scan:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
${setup}      - run: ${INSTALL[detection.packageManager]}
      - run: ${detection.buildCommand}
      - uses: inviy/evershield@v0
        with:
          path: ${detection.buildDir}
`;
}

export function renderConfig(): string {
  return `${JSON.stringify(
    {
      gate: { failOn: "high", minConfidence: "medium" },
      ignore: [],
    },
    null,
    2,
  )}\n`;
}

export interface InitResult {
  detection: Detection;
  written: string[];
  skipped: string[];
}

export async function runInit(root: string, options: { force?: boolean } = {}): Promise<InitResult> {
  const detection = await detectProject(root);
  const files: Array<[string, string]> = [
    ["evershield.config.json", renderConfig()],
    [".github/workflows/evershield.yml", renderWorkflow(detection)],
  ];
  const written: string[] = [];
  const skipped: string[] = [];
  for (const [relative, content] of files) {
    const target = path.join(root, relative);
    if (!options.force && (await exists(target))) {
      skipped.push(relative);
      continue;
    }
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content);
    written.push(relative);
  }
  return { detection, written, skipped };
}
